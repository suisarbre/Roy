export const CPI_SERIES: AnnualSeries = {
  table: CPI_U_ANNUAL_AVERAGE,
  before: { kind: 'growth', annualRate: 0.015 },
  after: { kind: 'growth', annualRate: 0.025 },
  interpolation: 'geometric',
};

export function cpiAt(year: number): number {
  return valueAt(CPI_SERIES, year);
}

/**
 * 한 시점의 달러 금액을 다른 시점의 달러로 환산한다.
 * 예: convertDollars(20, 2024, 1975) → 2024년 20달러짜리 물건이 1975년엔 대략 얼마였나.
 * 게임 안의 모든 "그 시절 물가"는 2024년 기준 가격 하나만 정해두고 이 함수로 뽑는 걸 권장 —
 * 품목별 역사 가격표를 따로 들고 다닐 필요가 없다.
 */
export function convertDollars(amount: number, fromYear: number, toYear: number): number {
  return amount * (cpiAt(toYear) / cpiAt(fromYear));
}

/** 2024년 달러 기준 가격을 해당 연도 명목 가격으로. */
export function priceIn(year: number, price2024: number): number {
  return convertDollars(price2024, 2024, year);
}
