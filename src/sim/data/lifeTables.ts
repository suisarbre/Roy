const COHORT_YEARS = Object.keys(COHORT_LIFE_TABLES)
  .map(Number)
  .sort((a, b) => a - b);

const MAX_AGE = 119;

/** 출생연도·성별·나이(정수, 만 나이)의 1년 사망확률. */
export function annualDeathProbability(birthYear: number, sex: Sex, age: number): number {
  const x = Math.max(0, Math.min(MAX_AGE, Math.floor(age)));
  const first = COHORT_YEARS[0];
  const last = COHORT_YEARS[COHORT_YEARS.length - 1];
  if (birthYear <= first) return COHORT_LIFE_TABLES[first][sex][x];
  if (birthYear >= last) return COHORT_LIFE_TABLES[last][sex][x];

  let lo = first;
  let hi = last;
  for (const y of COHORT_YEARS) {
    if (y <= birthYear) lo = y;
    if (y >= birthYear) {
      hi = y;
      break;
    }
  }
  if (lo === hi) return COHORT_LIFE_TABLES[lo][sex][x];
  const t = (birthYear - lo) / (hi - lo);
  return COHORT_LIFE_TABLES[lo][sex][x] * (1 - t) + COHORT_LIFE_TABLES[hi][sex][x] * t;
}

/**
 * 한 달 동안의 사망확률 — 연 확률을 월 단위로 균등 분할: 1 - (1 - q)^(1/12).
 * 월 tick 시뮬레이션은 이 값에 건강 상태 배수(만성질환, 스트레스 등)를 곱해 쓰면 된다.
 * 주의: 이 기저율은 이미 "평균적인 사람의 흡연·질병·사고"를 전부 포함한다. 게임의 건강
 * 실타래가 사망 위험을 따로 더하면 이중 계산이 되니, 배수는 평균 1 근처가 되게 튜닝할 것.
 */
export function monthlyDeathProbability(birthYear: number, sex: Sex, age: number, hazardMultiplier = 1): number {
  const q = annualDeathProbability(birthYear, sex, age);
  const monthly = 1 - Math.pow(1 - q, 1 / 12);
  return Math.min(1, monthly * hazardMultiplier);
}

/** 출생 시점 기대수명(연속 근사). 검증·디버깅용. */
export function lifeExpectancyAtBirth(birthYear: number, sex: Sex): number {
  let survivors = 1;
  let personYears = 0;
  for (let age = 0; age <= MAX_AGE; age++) {
    const q = annualDeathProbability(birthYear, sex, age);
    personYears += survivors * (1 - q / 2);
    survivors *= 1 - q;
  }
  return personYears;
}

/** fromAge 생존자가 toAge까지 생존할 확률. */
export function survivalProbability(birthYear: number, sex: Sex, fromAge: number, toAge: number): number {
  let p = 1;
  for (let age = Math.floor(fromAge); age < Math.floor(toAge); age++) {
    p *= 1 - annualDeathProbability(birthYear, sex, age);
  }
  return p;
}

/**
 * 지연 평가(NPC 승격 시 궤적 일괄 샘플링)용 — fromAge 생존자가 몇 살에 죽는지 한 번에 뽑는다.
 * 반환값이 NPC의 "예정 사망 나이"가 되고, 그 전까지는 시뮬레이션 없이도 살아있다고 볼 수 있다.
 * 반환값은 만 나이(그 해 안 어딘가에서 사망)라 평균이 기대수명보다 약 0.5년 작다 — 정상이다.
 */
export function sampleAgeAtDeath(birthYear: number, sex: Sex, fromAge: number, rng: Rng): number {
  for (let age = Math.floor(fromAge); age <= MAX_AGE; age++) {
    if (rng() < annualDeathProbability(birthYear, sex, age)) return age;
  }
  return MAX_AGE;
}
